import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { setTimeout as sleep } from 'node:timers/promises';
import { chromium } from 'playwright';
const out = process.env.BLASTER_SCREENSHOTS;
const origin = 'http://127.0.0.1:5192/';
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--port', '5192', '--strictPort', '--host', '127.0.0.1'], { stdio: 'ignore' });
let browser;
try {
  for (let i = 0; i < 150; i++) { try { if ((await fetch(origin)).ok) break; } catch {} await sleep(200); }
  browser = await chromium.launch({ channel: 'msedge' }).catch(() => chromium.launch());
  const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(origin + '?mars');
  await page.waitForFunction(() => window.atv?.game?.scene.isActive('Mars') && !window.atv.game.scene.getScene('Mars').flying, null, { timeout: 30000 });
  await page.evaluate(() => { const m = window.atv.game.scene.getScene('Mars'); m.player.setPosition(130, -60); });
  await sleep(300);
  if (out) await page.screenshot({ path: `${out}/mars-cabinet.png` });
  await page.evaluate(() => { const m = window.atv.game.scene.getScene('Mars'); m.player.setPosition(130, -18); });
  await page.waitForFunction(() => window.atv.game.scene.isActive('Blaster'));
  await sleep(500);
  if (out) await page.screenshot({ path: `${out}/title.png` });
  await page.keyboard.press('Space');
  await sleep(200);
  assert.equal(await page.evaluate(() => window.atv.game.scene.getScene('Blaster').state), 'play');
  await page.keyboard.down('ArrowLeft'); await sleep(600); await page.keyboard.up('ArrowLeft');
  await sleep(6000);
  if (out) await page.screenshot({ path: `${out}/play.png` });
  await page.evaluate(() => { const b = window.atv.game.scene.getScene('Blaster'); b.safe = 999; b.waveClock = 19.9; b.wave = 4; });
  await sleep(3500);
  if (out) await page.screenshot({ path: `${out}/boss.png` });
  await page.keyboard.press('Space');
  await sleep(400);
  const after = await page.evaluate(() => { const b = window.atv.game.scene.getScene('Blaster'); return { bombs: b.bombs, boss: !!b.boss, hp: b.boss?.hp, score: b.score }; });
  assert.equal(after.bombs, 2, 'space drops a smart bomb');
  assert.ok(after.boss && after.hp < 100, 'the mothership arrives on wave 5 and the bomb hurts it');
  await page.evaluate(() => { const b = window.atv.game.scene.getScene('Blaster'); b.safe = 0; b.shielded = false; b.lives = 1; b.score = 1300; b.hit(); });
  await sleep(300);
  if (out) await page.screenshot({ path: `${out}/over.png` });
  const tokens = await page.evaluate(() => localStorage.getItem('atv-tokens'));
  assert.equal(await page.evaluate(() => window.atv.game.scene.getScene('Blaster').state), 'over', 'last life lost ends the game');
  assert.equal(Number(tokens), 2, '1300 points earns two gold tokens');
  assert.equal(await page.evaluate(() => localStorage.getItem('atv-blaster-best')), '1300', 'best score is saved');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => window.atv.game.scene.isActive('Mars') && !window.atv.game.scene.isActive('Blaster'));
  await sleep(500);
  assert.ok(await page.evaluate(() => window.atv.game.scene.getScene('Mars').atArcade), 'standing at the cabinet does not relaunch it');
  assert.deepEqual(errors, [], 'no game errors');
  console.log('Mars Blaster: cabinet, title, play, boss, bomb, game over, tokens, best score and leaving passed.');
} finally { await browser?.close(); server.kill(); }
